export async function analyzeContract(
  contractText: string,
  imageBase64?: string,
  imageMimeType?: string
): Promise<AnalysisResult> {
  const messageContent: Anthropic.MessageParam['content'] = []

  if (imageBase64 && imageMimeType) {
    messageContent.push({
      type: 'image',
      source: {
        type: 'base64',
        media_type: imageMimeType as 'image/jpeg' | 'image/png' | 'image/gif' | 'image/webp',
        data: imageBase64,
      },
    })
    messageContent.push({
      type: 'text',
      text: `上記の契約書画像を分析してください。

【分析手順】
STEP1: 契約書から以下を特定してください
- 支払期日に関する条項（日数を数値で確認）
- 解除・終了に関する条項（即時解除の可否・予告期間）
- 報酬・単価変更に関する条項
- 修正・やり直しに関する条項
- 返品・受領拒否に関する条項
- 書面明示事項の記載状況

STEP2: 各条項をデータベースの条文と照合し、違反リスクを判定してください。
STEP3: JSONを出力してください。`,
    })
  } else {
    messageContent.push({
      type: 'text',
      text: `以下の契約書を分析してください。

【分析手順】
STEP1: 契約書から以下を特定してください
- 支払期日に関する条項（日数を数値で確認）
- 解除・終了に関する条項（即時解除の可否・予告期間）
- 報酬・単価変更に関する条項
- 修正・やり直しに関する条項
- 返品・受領拒否に関する条項
- 書面明示事項の記載状況

STEP2: 各条項をデータベースの条文と照合し、違反リスクを判定してください。
STEP3: JSONを出力してください。

━━━━ 契約書本文 ━━━━
${contractText}
━━━━━━━━━━━━━━━━`,
    })
  }

  const response = await client.messages.create({
    model: 'claude-sonnet-4-6',
    max_tokens: 8192,
    system: SYSTEM_PROMPT,
    messages: [{ role: 'user', content: messageContent }],
  })

  const content = response.content[0]
  if (content.type !== 'text') {
    throw new Error('Claude APIから予期しないレスポンス形式が返されました')
  }

  const jsonMatch = content.text.match(/\{[\s\S]*\}/)
  if (!jsonMatch) {
    throw new Error('Claude APIのレスポンスからJSONが見つかりませんでした')
  }

  const result = JSON.parse(jsonMatch[0]) as AnalysisResult

  // disclaimer が未設定の場合のフォールバック
  if (!result.disclaimer) {
    result.disclaimer =
      '本分析はAIによる一次チェックです。法律相談ではありません。重要な契約は必ず弁護士にご相談ください。'
  }

  // missing_clauses が未設定の場合のフォールバック
  if (!result.missing_clauses) {
    result.missing_clauses = []
  }

  return result
}
